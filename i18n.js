let LOCALE = 'en';

function setLocale(l) {
    LOCALE = (l === 'en' || I18N[l]) ? l : 'en';
    document.documentElement.lang = LOCALE;
}

// Read the language on every call, not from the cached LOCALE: clock-network.js
// is a non-deferred script that writes diagnostics values before applyI18n has
// ever run, and its async probes land at arbitrary times afterwards.
function t(key) {
    const dict = I18N[currentFleetLang()];
    return (dict && dict[key]) || key;
}

// Static markup: elements carrying data-i18n use their original English text
// as the key (captured on first pass so locale switches stay reversible).
function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim();
        el.textContent = t(el.dataset.i18nKey);
    });
}

// Prominent title attributes (brand links, the GitHub icon) — explicit, not via data-i18n.
function applyTitleI18n() {
    document.querySelectorAll('.brand-name a[title], .social-row a[href*="github.com"][title]').forEach((el) => {
        if (!el.dataset.i18nTitle) el.dataset.i18nTitle = el.getAttribute('title');
        el.setAttribute('title', t(el.dataset.i18nTitle));
    });
}

// Wiring: carino-lang.js (deferred, loaded before this script) owns the
// language; we re-render on load and on every fleet-wide language switch.
function currentFleetLang() {
    return (window.CarinoLang && window.CarinoLang.current) || 'en';
}

function applyI18n() {
    setLocale(currentFleetLang());
    applyStaticI18n();
    applyTitleI18n();
    // The tool cards are built from JSON, not markup, so data-i18n never
    // sees them — index.html re-renders the grid with the new locale.
    if (typeof window.renderTools === 'function') window.renderTools();
}

document.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);
