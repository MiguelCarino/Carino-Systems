#!/usr/bin/env python3
"""apply.py — write the generated baseline files into every Carino site.

    python3 apply.py              # dry run: list what would change
    python3 apply.py --write      # write the changes
    python3 apply.py --write --adopt robots.txt   # also replace a hand-made robots.txt
    python3 apply.py ping.carino.systems ...      # only these sites

Reads sites.json (one entry per site) and the files in templates/, and
writes four things into each site's folder:

    robots.txt    allow everything, point at the sitemap
    sitemap.xml   the site's root, plus any extra "pages" listed in sites.json
    404.html      the shared not-found page
    AUDIT.md      the provenance ledger, at the repository root; created
                  once if missing and never touched again
    index.html    only the block between <!-- carino:head --> and
                  <!-- /carino:head -->: description, canonical URL, Open Graph
                  tags and schema.org JSON-LD

Every generated file starts with a "generated by" line. A file without that
line was made by hand, and is never overwritten unless named in --adopt.

The first time a page gets the head block, its own description, canonical and
og: tags are removed from the head, so the block holds the only copy. The
description itself comes from sites.json, which was seeded from each page's
own description, or the hub registry's where a page had none.

Standard library only. Paths are relative to the folder holding all the repos
(two levels up from this file).
"""
import html
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPOS = HERE.parent.parent
MARK = 'generated by Carino-Systems/baseline/apply.py'
AUTHOR = 'Miguel Cariño'
HUB = 'https://carino.systems/'


def template(name):
    return (HERE / 'templates' / name).read_text(encoding='utf-8')


def fill(text, **values):
    for k, v in values.items():
        text = text.replace('{{' + k + '}}', v)
    return text


def json_ld(site):
    """schema.org description of the site. The hub is a WebSite; a page that
    describes installable software (sites.json "software": its OS list) is a
    SoftwareApplication; every other site is a WebApplication."""
    url = 'https://' + site['domain'] + '/'
    author = {'@type': 'Person', 'name': AUTHOR}
    if not site.get('standalone'):
        author['url'] = HUB
    if site.get('hub'):
        data = {'@type': 'WebSite', 'name': site['name'], 'url': url,
                'description': site['desc'], 'publisher': author}
    elif site.get('software'):
        data = {'@type': 'SoftwareApplication', 'name': site['name'], 'url': url,
                'description': site['desc'], 'operatingSystem': site['software'],
                'isAccessibleForFree': True, 'author': author}
    else:
        data = {'@type': 'WebApplication', 'name': site['name'], 'url': url,
                'description': site['desc'], 'operatingSystem': 'Any (runs in a web browser)',
                'isAccessibleForFree': True, 'author': author}
    data = {'@context': 'https://schema.org', **data}
    # "</" would end the <script> element early, whatever the JSON says.
    return json.dumps(data, ensure_ascii=False).replace('</', '<\\/')


def image_tag(site):
    """og:image line, or nothing. sites.json "image" names the file; otherwise
    the site's logo.webp if it has one. SVG-only sites get none: share
    previews do not render SVG."""
    rel = site.get('image') or 'logo.webp'
    if not (REPOS / site['dir'] / rel).exists():
        return ''
    return f'<meta property="og:image" content="https://{site["domain"]}/{rel}">\n'


def head_block(site):
    esc = lambda s: html.escape(s, quote=True)
    return fill(template('head.html').rstrip('\n'), image=image_tag(site),
                desc=esc(site['desc']), domain=site['domain'], name=esc(site['name']),
                site_name=esc(site['name'] if site.get('standalone') else 'Carino Systems'),
                jsonld=json_ld(site))


def sitemap(site):
    base = 'https://' + site['domain'] + '/'
    urls = [base] + [base + p for p in site.get('pages', [])]
    return fill(template('sitemap.xml'), urls='\n'.join(f'  <url><loc>{u}</loc></url>' for u in urls))


def page_404(site):
    hub = '' if site.get('standalone') or site.get('hub') else \
        f'<a class="alt" href="{HUB}">Carino Systems</a>'
    return fill(template('404.html'), name=html.escape(site['name']), hub_link=hub)


# Single-line tags the head block takes over the first time it is inserted.
OWNED = re.compile(r'^[ \t]*<(?:meta\s[^>]*(?:name="description"|property="og:[^"]*")'
                   r'|link\s[^>]*rel="canonical")[^>]*>[ \t]*\n', re.I | re.M)
BLOCK = re.compile(r'[ \t]*<!-- carino:head\b.*?<!-- /carino:head -->', re.S)
TITLE = re.compile(r'^([ \t]*)<title>.*?</title>[ \t]*\n', re.I | re.M | re.S)


def with_head(page, site):
    """index.html with the head block inserted or refreshed, or None if the
    page has no <title> to anchor it after."""
    if BLOCK.search(page):
        indent = re.search(r'([ \t]*)<!-- carino:head', page).group(1)
        block = '\n'.join(indent + line for line in head_block(site).split('\n'))
        return BLOCK.sub(lambda m: block, page, count=1)
    m = TITLE.search(page)
    if not m:
        return None
    indent = m.group(1)
    block = '\n'.join(indent + line for line in head_block(site).split('\n')) + '\n'
    head_end = page.lower().find('</head>')
    head, rest = page[:head_end], page[head_end:]
    head = OWNED.sub('', head)
    m = TITLE.search(head)
    return head[:m.end()] + block + head[m.end():] + rest


def main(argv):
    write = '--write' in argv
    adopt = set()
    if '--adopt' in argv:
        adopt = set(argv[argv.index('--adopt') + 1].split(','))
    only = {a for a in argv if '.' in a and not a.startswith('-') and a not in adopt}
    sites = json.loads((HERE / 'sites.json').read_text(encoding='utf-8'))
    changed = refused = 0
    for site in sites:
        if only and site['domain'] not in only:
            continue
        root = REPOS / site['dir']
        outputs = {'robots.txt': fill(template('robots.txt'), domain=site['domain']),
                   'sitemap.xml': sitemap(site), '404.html': page_404(site)}
        # The audit ledger lives at the repository root and belongs to the person
        # who fills it in: it is created once, from the template, and never rewritten.
        ledger = REPOS / site['dir'].split('/')[0] / 'AUDIT.md'
        if not ledger.exists():
            print(f'  {"created" if write else "would create"} {ledger.relative_to(REPOS)}')
            changed += 1
            if write:
                ledger.write_text(template('AUDIT.md'), encoding='utf-8')
        index = root / 'index.html'
        page = index.read_text(encoding='utf-8')
        new = with_head(page, site)
        if new is None:
            print(f'  ! {site["domain"]}: index.html has no <title>; head block skipped')
            refused += 1
        else:
            outputs['index.html'] = new
        for name, text in outputs.items():
            path = root / name
            old = path.read_text(encoding='utf-8') if path.exists() else None
            if old == text:
                continue
            if old is not None and name != 'index.html' and MARK not in old and name not in adopt:
                print(f'  ! {site["domain"]}: {name} was made by hand; left alone (--adopt {name} to replace)')
                refused += 1
                continue
            print(f'  {"wrote" if write else "would write"} {site["dir"]}/{name}')
            changed += 1
            if write:
                path.write_text(text, encoding='utf-8')
    print(f'{changed} file(s) {"written" if write else "to write"}, {refused} refused.')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
