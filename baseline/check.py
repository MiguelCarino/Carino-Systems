#!/usr/bin/env python3
"""check.py — verify the fleet baseline. Read-only: it changes nothing.

    python3 check.py                 # files on disk
    python3 check.py --live          # also ask the live sites (HTTPS, robots, sitemap, 404)
    python3 check.py --provenance    # AUDIT.md: reviewed / ai counts, stale reviews
    python3 check.py --types         # page-type gate: does each site have its type's blocks?
    python3 check.py --report        # write REPORT.md with everything above
    python3 check.py ping.carino.systems ...   # only these sites

A check passes only when this script verified it; nothing is taken on trust.
Exit status is 1 when any check fails, so it can gate a commit.
.github/workflows/fleet-check.yml runs it (and --types) every day on fresh
clones of every site's repository, and opens a "Fleet check failed" issue.

Each check below states its method in its docstring. The item numbers are the
20-point checklist in docs/BASELINE-SCOPE.md. Items that are decisions rather
than code (8, 18, 20) are reported as such, and items that need a browser
(12, 13, 14) as "not measured" until that pass exists.

Standard library only.
"""
import json
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPOS = HERE.parent.parent
MARK = 'generated by Carino-Systems/baseline/apply.py'
LEGAL = 'carino.systems/legal.html'

# The canonical copy of each shared file, as named in propagate.sh.
SHARED = {
    'carino-navbar.js': 'CVE/carino-navbar.js',
    'carino-clock.js': 'Carino-Systems/carino-clock.js',
    'carino-lang.js': 'Carino-Systems/carino-lang.js',
    'carino-bridge.js': 'Quote/carino-bridge.js',
    'carino-diag.js': 'Topo/carino-diag.js',
    'carino-anim.css': 'Branding/carino-anim.css',
    'carino-anim.js': 'Branding/carino-anim.js',
    'carino-ui.css': 'Branding/carino-ui.css',
    'carino-ui.js': 'Branding/carino-ui.js',
}
TRACKERS = re.compile(r'googletagmanager\.com|google-analytics\.com|gtag\(\s*[\'"]config|plausible\.io/js'
                      r'|umami\.is|goatcounter\.com/count|clarity\.ms/tag|static\.cloudflareinsights\.com'
                      r'|connect\.facebook\.net|hotjar\.com', re.I)
COMMENTS = re.compile(r'<!--.*?-->|/\*.*?\*/|^[ \t]*//[^\n]*', re.S | re.M)
CODE = ('.html', '.js', '.mjs', '.cjs', '.css', '.py', '.sh', '.ts')
SKIP = re.compile(r'(^|/)(vendor|node_modules|fonts|\.history)/|\.min\.(js|css)$')


def git_files(repo, sub=''):
    # Tracked files plus new ones not ignored, so a file added but not yet
    # committed (a freshly copied shared file) counts as present.
    out = subprocess.run(['git', '-C', str(REPOS / repo), 'ls-files', '--cached', '--others', '--exclude-standard']
                         + ([sub] if sub else []),
                         capture_output=True, text=True).stdout.split()
    return [f[len(sub) + 1:] if sub else f for f in out]


def read(path):
    try:
        return path.read_text(encoding='utf-8', errors='ignore')
    except OSError:
        return ''


class Site:
    def __init__(self, entry):
        self.e = entry
        self.domain = entry['domain']
        self.repo, _, self.sub = entry['dir'].partition('/')
        self.root = REPOS / entry['dir']
        self.files = git_files(self.repo, self.sub)
        self.index = read(self.root / 'index.html')
        self.head = self.index[:self.index.lower().find('</head>')]


# ---- the checks: each returns (ok, note); ok None means "not applicable" ----

def c_legal(s):
    """1-3 Legal, privacy, cookies: the page links to carino.systems/legal.html,
    directly or through a shared navbar copy that carries the link."""
    if s.e.get('standalone'):
        return None, 'standalone product, own licence'
    if LEGAL in s.index:
        return True, ''
    if 'carino-navbar.js' in s.index and LEGAL in read(s.root / 'carino-navbar.js'):
        return True, 'via navbar'
    return False, 'no link to ' + LEGAL


def c_meta(s):
    """5 Title and description: a non-empty <title> and meta description in the head."""
    t = re.search(r'<title>\s*[^<\s][^<]*</title>', s.head, re.I)
    d = re.search(r'<meta[^>]+name="description"[^>]+content="[^"]{20,}"', s.head, re.I)
    return bool(t and d), '' if t and d else ('no title' if not t else 'no description')


def c_jsonld(s):
    """6 Structured data: one application/ld+json block that parses, with @type."""
    m = re.search(r'<script type="application/ld\+json">(.*?)</script>', s.head, re.S)
    if not m:
        return False, 'none'
    try:
        return '@type' in json.loads(m.group(1)), ''
    except ValueError as e:
        return False, 'does not parse: ' + str(e)


def c_robots(s):
    """7 robots.txt and sitemap.xml exist, and robots names the sitemap."""
    r = read(s.root / 'robots.txt')
    ok = 'Sitemap: https://' + s.domain + '/sitemap.xml' in r and (s.root / 'sitemap.xml').exists()
    return ok, '' if ok else 'missing or not linked'


def c_favicon(s):
    """9 Favicon: a rel=icon link whose file exists in the repo."""
    m = re.search(r'<link[^>]+rel="(?:shortcut )?icon"[^>]+href="([^"]+)"', s.head, re.I) or \
        re.search(r'<link[^>]+href="([^"]+)"[^>]+rel="(?:shortcut )?icon"', s.head, re.I)
    if not m:
        return False, 'no icon link'
    return m.group(1).lstrip('./') in s.files, '' if m.group(1).lstrip('./') in s.files else 'file missing'


def c_alt(s):
    """10 Alt text: every <img> written in the site's HTML (comments removed)
    has an alt attribute; alt="" is correct for decorative images."""
    bad = []
    for f in s.files:
        if f.endswith('.html') and not SKIP.search(f):
            for m in re.finditer(r'<img\b[^>]*>', COMMENTS.sub('', read(s.root / f)), re.I):
                if not re.search(r'\balt\s*=', m.group(0), re.I):
                    bad.append(f)
    return not bad, f'{len(bad)} without alt' if bad else ''


def c_images(s):
    """11 Compressed images: no image over 300 KB that a page, script or
    stylesheet of the site refers to by name."""
    text = ''.join(read(s.root / f) for f in s.files if f.endswith(('.html', '.css', '.js')) and not SKIP.search(f))
    big = [f for f in s.files if f.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.webp', '.bmp'))
           and (s.root / f).exists() and (s.root / f).stat().st_size > 300_000 and Path(f).name in text]
    return not big, ', '.join(big)


def c_404(s):
    """15 Custom 404: a 404.html at the site root."""
    return (s.root / '404.html').exists(), ''


def c_links(s):
    """16 Broken local links: every relative href/src in index.html names a file in the repo."""
    miss = []
    for u in re.findall(r'(?<![\w-])(?:href|src)="([^"#?]+)', COMMENTS.sub('', s.index)):
        # Skip absolute URLs and anything assembled by script ('+x+', ${x}).
        if re.match(r'[a-z]+:|//|\$|\{', u) or re.search(r"\$\{|'\s*\+|\+\s*'", u):
            continue
        u = u.lstrip('./').rstrip('/')
        if u and u not in s.files and not any(f.startswith(u + '/') for f in s.files):
            miss.append(u)
    return not miss, ', '.join(miss[:4])


def c_forms(s):
    """17 Spam-protected forms: no form posts to a server (none should exist)."""
    posts = [f for f in s.files if f.endswith('.html') and
             re.search(r'<form[^>]+action="https?://', read(s.root / f), re.I)]
    return not posts, ', '.join(posts)


def c_analytics(s):
    """19 No analytics, deliberately: no known tracker appears in any served file."""
    hits = [f for f in s.files if f.endswith(('.html', '.js')) and not SKIP.search(f)
            and TRACKERS.search(read(s.root / f))]
    return not hits, ('tracker in ' + ', '.join(hits)) if hits else 'none, by decision'


def c_fontlic(s):
    """Font licences: every folder holding font files has their licence text
    (OFL.txt, LICENSE...) beside it or in a folder above it, as the SIL OFL
    requires it to travel with the files."""
    lic = {str(Path(f).parent) for f in s.files if re.search(r'(ofl|licen[cs]e|copying)', Path(f).name, re.I)}
    dirs = {Path(f).parent for f in s.files if f.lower().endswith(('.woff2', '.woff', '.ttf', '.otf'))}
    bare = sorted(str(d) for d in dirs if not any(str(p) in lic for p in [d, *d.parents] if str(p) != '.'))
    return not bare, ', '.join(bare)


def c_shared(s):
    """Shared files match their canonical copy (propagate.sh keeps them in step)."""
    drift = [n for n, src in SHARED.items()
             if (s.root / n).exists() and (s.root / n).resolve() != (REPOS / src).resolve()
             and read(s.root / n) != read(REPOS / src)]
    return not drift, 'differs: ' + ', '.join(drift) if drift else ''


STATIC = [('legal', c_legal), ('meta', c_meta), ('jsonld', c_jsonld), ('robots', c_robots),
          ('favicon', c_favicon), ('alt', c_alt), ('images', c_images), ('404', c_404),
          ('links', c_links), ('forms', c_forms), ('analytics', c_analytics), ('fontlic', c_fontlic),
          ('shared', c_shared)]


# ---- page types (--types) ----
# What each page type must contain, as defined in Branding #pagetypes. The
# method is static: a block counts when its production class from
# carino-ui.css appears in the site's own HTML or JS (a class a script builds
# counts). That proves the block is used, not that it looks right; the
# browser pass checks the look.

UI_TOKENS = re.findall(r'^\s*(--[\w-]+)\s*:', read(REPOS / 'Branding/carino-ui.css').split('}')[0], re.M)


def own_files(s, exts):
    # Wholly generated files (404.html, …) are not the site's own; index.html
    # only carries a generated <head> block, so it always counts.
    return [f for f in s.files if f.endswith(exts) and not SKIP.search(f) and Path(f).name not in SHARED
            and (f == 'index.html' or MARK not in read(s.root / f)[:300])]


HTML_COMMENTS = re.compile(r'<!--.*?-->', re.S)
JS_COMMENTS = re.compile(r'/\*.*?\*/|^[ \t]*//[^\n]*', re.S | re.M)


def own_text(s):
    # Each language's own comments only: a "/*" inside HTML text is not a comment.
    return '\n'.join((HTML_COMMENTS if f.endswith('.html') else JS_COMMENTS).sub('', read(s.root / f))
                     for f in own_files(s, ('.html', '.js', '.mjs')))


def uses(s, *classes):
    text = getattr(s, '_own', None)
    if text is None:
        text = s._own = own_text(s)
    return [c for c in classes if not re.search(r'(?<![\w-])' + re.escape(c) + r'(?![\w-])', text)]


TYPE_BLOCKS = {
    'hub':       [('landing-hero',), ('site-foot',)],
    'tool':      [('short-hero',), ('privacy-line',), ('ws', 'col')],
    'suite':     [('short-hero',), ('slice-menu',), ('privacy-line',), ('CarinoUI.slices',)],
    'live':      [('live-chip',), ('fresh',), ('data-foot',)],
    'reference': [('landing-hero',), ('fchips',), ('src-line',), ('site-foot',)],
    'learn':     [('landing-hero', 'short-hero'), ('privacy-line',), ('site-foot',)],
    'play':      [('play-stage',), ('prefers-reduced-motion',)],
    'product':   [('landing-hero',), ('sys-line',), ('term-copy',), ('privacy-line',), ('site-foot',)],
}


def t_ui(s):
    """Shared UI: index.html links carino-ui.css, and the copy matches Branding's."""
    if s.e.get('standalone'):
        return None, 'standalone product'
    linked = re.search(r'<link[^>]+href="(?:\./)?carino-ui\.css"', s.head) or any(
        re.search(r'@import\s+url\(["\']?(?:\./)?carino-ui\.css', read(s.root / h.lstrip('./')))
        for h in re.findall(r'<link[^>]+rel="stylesheet"[^>]+href="([^":]+\.css)"', s.head))
    if not linked:
        return False, 'carino-ui.css not linked'
    return read(s.root / 'carino-ui.css') == read(REPOS / 'Branding/carino-ui.css'), ''


def strip_media(css, *queries):
    """Remove whole @media blocks whose condition mentions any of `queries`."""
    out, i = [], 0
    for m in re.finditer(r'@media[^{]*\{', css):
        if m.start() < i or not any(q in m.group(0) for q in queries):
            continue
        depth, j = 1, m.end()
        while j < len(css) and depth:
            depth += {'{': 1, '}': -1}.get(css[j], 0)
            j += 1
        out.append(css[i:m.start()])
        i = j
    return ''.join(out) + css[i:]


def t_tokens(s):
    """No token redefined: the site's own CSS (stylesheets and inline <style>)
    declares none of the custom properties carino-ui.css declares. New names
    are fine; Branding's names keep Branding's values. A print or
    high-contrast palette (@media print, prefers-contrast) may override them."""
    if s.e.get('standalone'):
        return None, 'standalone product'
    hits = set()
    for f in own_files(s, ('.css', '.html')):
        text = read(s.root / f)
        if f.endswith('.html'):
            text = '\n'.join(re.findall(r'<style[^>]*>(.*?)</style>', text, re.S | re.I))
        text = strip_media(JS_COMMENTS.sub('', text), 'print', 'prefers-contrast')
        for t in UI_TOKENS:
            if re.search(r'(?<![\w-])' + re.escape(t) + r'\s*:', text):
                hits.add(t)
    return not hits, ', '.join(sorted(hits)[:6]) + (' …' if len(hits) > 6 else '')


def t_blocks(s):
    """The type's blocks: every required block's class is used (any one of the
    alternatives in a group). Standalone products need only a footer and
    copyable commands."""
    kind = s.e.get('type')
    if not kind:
        return False, 'no type in sites.json'
    if s.e.get('standalone'):
        text = own_text(s)
        miss = [n for n, rx in (('footer', r'<footer'), ('copy', r'copy')) if not re.search(rx, text, re.I)]
        return not miss, 'missing: ' + ', '.join(miss) if miss else 'layout only'
    miss = [' or '.join(g) for g in TYPE_BLOCKS.get(kind, []) if len(uses(s, *g)) == len(g)]
    return not miss, 'missing: ' + ', '.join(miss) if miss else kind


def t_priority(s):
    """Main action: a page that puts controls in the navbar marks the one to
    keep on phones (data-priority="1", or a primary button among them)."""
    # The element itself, not a mention of the attribute in a comment or CSS.
    m = re.search(r'<[a-z][\w-]*\b[^>]*\sdata-carino-actions\b', HTML_COMMENTS.sub('', s.index))
    if not m:
        return None, 'no navbar controls'
    html = HTML_COMMENTS.sub('', s.index)
    block = html[m.start():][:6000]
    ok = re.search(r'data-priority="1"|btn-primary|cs-btn primary|class="[^"]*\bprimary\b', block) is not None
    return ok, '' if ok else 'no data-priority="1" or primary'


TYPES = [('ui', t_ui), ('tokens', t_tokens), ('blocks', t_blocks), ('priority', t_priority)]


# ---- live checks (--live) ----

class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


def status(url, follow=True):
    opener = urllib.request.build_opener() if follow else urllib.request.build_opener(NoRedirect)
    try:
        r = opener.open(urllib.request.Request(url, method='GET', headers={'User-Agent': 'carino-baseline-check'}), timeout=15)
        return r.status, r.headers.get('Location', '')
    except urllib.error.HTTPError as e:
        return e.code, e.headers.get('Location', '')
    except (urllib.error.URLError, OSError) as e:
        return 0, str(getattr(e, 'reason', e))


def c_https(s):
    """4 Force HTTPS: http:// answers 301 to https://, and https:// answers 200."""
    code, loc = status(f'http://{s.domain}/', follow=False)
    ok = code == 301 and loc.startswith('https://')
    secure = status(f'https://{s.domain}/')[0] == 200
    return ok and secure, '' if ok and secure else f'http {code}, https {"ok" if secure else "fails"}'


def c_live_files(s):
    """7, 15 live: robots.txt and sitemap.xml answer 200; a missing page answers 404."""
    r = status(f'https://{s.domain}/robots.txt')[0]
    m = status(f'https://{s.domain}/sitemap.xml')[0]
    n = status(f'https://{s.domain}/carino-baseline-missing-page')[0]
    ok = r == 200 and m == 200 and n == 404
    return ok, '' if ok else f'robots {r}, sitemap {m}, missing page {n}'


LIVE = [('https', c_https), ('served', c_live_files)]


# ---- provenance (--provenance) ----

ROW = re.compile(r'^\|\s*`?([^|`]+?)`?\s*\|\s*`?(ai|reviewed|human)`?\s*\|[^|]*\|[^|]*\|\s*`?([0-9a-f]{7,40})?`?\s*\|', re.M)


def provenance(repo):
    """Counts from AUDIT.md: code files in the repo, how many are reviewed or
    human, and which reviews went stale (the file changed after its commit)."""
    files = git_files(repo)
    code = [f for f in files if f.endswith(CODE) and not SKIP.search(f) and Path(f).name not in SHARED
            and (f == 'index.html' or MARK not in read(REPOS / repo / f)[:300])]
    ledger = read(REPOS / repo / 'AUDIT.md')
    if not ledger:
        return None
    rows = {m.group(1).strip(): (m.group(2), m.group(3)) for m in ROW.finditer(ledger)}
    reviewed = human = 0
    stale = []
    for f, (st, commit) in rows.items():
        if f not in code:
            continue
        if st == 'human':
            human += 1
        elif st == 'reviewed':
            changed = subprocess.run(['git', '-C', str(REPOS / repo), 'diff', '--quiet', commit or 'HEAD', '--', f]).returncode
            (stale.append(f) if (not commit or changed) else None)
            reviewed += 0 if (not commit or changed) else 1
    return {'files': len(code), 'reviewed': reviewed, 'human': human, 'stale': stale,
            'ai': len(code) - reviewed - human - len(stale)}


# ---- output ----

def main(argv):
    live, prov, report = '--live' in argv, '--provenance' in argv or '--report' in argv, '--report' in argv
    types = '--types' in argv or report
    live = live or report
    only = {a for a in argv if not a.startswith('-')}
    sites = [Site(e) for e in json.loads((HERE / 'sites.json').read_text(encoding='utf-8'))
             if not only or e['domain'] in only]
    checks = (TYPES if '--types' in argv and not report else STATIC + (LIVE if live else []) + (TYPES if types else []))
    names = [n for n, _ in checks]
    fails, lines = 0, []
    lines.append('| Site | ' + ' | '.join(names) + ' |')
    lines.append('|---' * (len(names) + 1) + '|')
    notes = []
    for s in sites:
        cells = []
        for n, fn in checks:
            ok, note = fn(s)
            cells.append('–' if ok is None else '✓' if ok else '✗')
            if ok is False:
                fails += 1
                notes.append(f'- **{s.domain}** {n}: {note}')
        lines.append(f'| {s.domain} | ' + ' | '.join(cells) + ' |')
    out = ['# Fleet baseline report', '',
           'Generated by `Carino-Systems/baseline/check.py --report`. ✓ = verified by the script,',
           '✗ = failed, – = not applicable. Methods: the docstring of each check in check.py.', '',
           '## Checks', ''] + lines + ['']
    out += ['### Failures', ''] + (notes or ['None.']) + ['']
    out += ['### Not checked by script', '',
            '- 8 Google Business Profile, 18 WhatsApp button: **deliberately absent** (decision 2026-10-19).',
            '- 19 Analytics: **deliberately none**; the `analytics` column guards it.',
            '- 12 Load speed, 13 Colour contrast, 14 Mobile layout: **not measured yet** (needs the browser pass, scope §3.7).',
            '- 20 Single call to action: **skipped** for now (decision 2026-10-20).', '']
    if prov:
        out += ['## Provenance', '',
                'From each repository\'s AUDIT.md. Code files exclude generated, shared, vendored and font files.', '',
                '| Repository | Code files | Reviewed | Human | Stale | AI, unreviewed |', '|---|---|---|---|---|---|']
        for repo in sorted({s.repo for s in sites}, key=str.lower):
            p = provenance(repo)
            if p is None:
                out.append(f'| {repo} | – | – | – | – | no AUDIT.md |')
                fails += 1
                continue
            out.append(f'| {repo} | {p["files"]} | {p["reviewed"]} | {p["human"]} | {len(p["stale"])} | {p["ai"]} |')
        out.append('')
    text = '\n'.join(out)
    if report:
        (HERE / 'REPORT.md').write_text(text, encoding='utf-8')
        print(f'wrote REPORT.md — {fails} failure(s)')
    else:
        print(text)
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
